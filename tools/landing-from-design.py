"""Builds the repo-root index.html (static landing, no JS) from the design's rendered landing.html markup.
usage: python3 tools/landing-from-design.py /tmp/ld-1440.html > index.html
(the input is document.getElementById('root').innerHTML of design screens/src/landing.html, rendered in Chrome)."""
import re, sys
s = open(sys.argv[1]).read()

def svg(m):
    attrs, body = m.group(1), m.group(2)
    rows = {}
    for x, y, w, h in re.findall(r'<rect x="(\d+)" y="(\d+)" width="(\d+)" height="(\d+)"></rect>', body):
        rows.setdefault(int(y), []).append(int(x))
    d = []
    for y in sorted(rows):
        xs = sorted(rows[y]); i = 0
        while i < len(xs):
            j = i
            while j + 1 < len(xs) and xs[j + 1] == xs[j] + 1: j += 1
            d.append(f'M{xs[i]} {y}h{xs[j] - xs[i] + 1}v1h-{xs[j] - xs[i] + 1}z'); i = j + 1
    fill = re.search(r'fill="([^"]*)"', attrs)
    attrs = re.sub(r'\s*fill="[^"]*"', '', attrs)
    return f'<svg{attrs}><path fill="{fill.group(1) if fill else "currentColor"}" d="{"".join(d)}"/></svg>'
s = re.sub(r'<svg([^>]*)>(.*?)</svg>', svg, s, flags=re.S)

A = '/Pixeldate/'
s = s.replace('<img src="../../assets/art/landing-hero-wide.webp"',
  f'<picture><source media="(min-width: 768px)" srcset="{A}art/landing-hero-wide.webp" width="1280" height="720"><img src="{A}art/landing-hero-tall.webp" width="864" height="1152" decoding="async"')
s = re.sub(r'(fetchpriority="high">)', r'\1</picture>', s, count=1)
for n in ('8', '16', '32', '64', 'full'):
    s = s.replace(f'../../assets/photos/juno-{n}.webp"', f'{A}art/ld/juno-{n}.webp" width="480" height="480" decoding="async"')
# small avatars stay coarse (spec 4): the demo card uses 6-block avatars
s = s.replace('../../assets/photos/kofi-full.webp"', f'{A}art/ld/kofi-6.webp" width="96" height="96" loading="lazy"')
s = s.replace('../../assets/photos/rae-6.webp"', f'{A}art/ld/rae-6.webp" width="96" height="96" loading="lazy"')
# nav + CTAs become real links
s = s.replace('<span class="lk"><a>How it works</a><a>Question cards</a><a>Safety</a></span>',
  '<span class="lk"><a href="#how">How it works</a><a href="#cards">Question cards</a><a href="#safety">Safety</a></span>')
s = re.sub(r'<span class="(btn[^"]*)">((?:Try it now|Sign up|Sign up, it\'s free)(?:<svg.*?</svg>)?)</span>', r'<a class="\1" href="./app/">\2</a>', s)
s = s.replace('<nav class="ld-nav">', '<nav class="ld-nav" aria-label="Pixeldate">')
s = s.replace('<span class="logo" style="--logo:30px">', '<a class="logo" style="--logo:30px" href="./" aria-label="Pixeldate home">', 1)
s = s.replace('<span>pixel<b>date</b></span></span><span class="lk">', '<span>pixel<b>date</b></span></a><span class="lk">', 1)
sec = iter(['how', 'cards', 'safety'])
s = re.sub(r'<section class="ld-sec">', lambda m: f'<section class="ld-sec" id="{next(sec)}">', s)
s = s.replace('</header>\n<section', '</header>\n<main>\n<section', 1).replace('</section>\n<footer', '</section>\n</main>\n<footer', 1)
s = s.replace('role="meter" aria-valuenow="60"', 'role="meter" aria-valuenow="60" aria-valuemin="0" aria-valuemax="100" aria-label="Meter: 60% to Crush"')
s = s.replace('<div class="demo2">', '<div class="demo2" role="img" aria-label="Two example question cards">')
s = re.sub(r'class="hp\s+"', 'class="hp"', s).replace(' style=""', '').replace('qcard fx "', 'qcard fx"')
# contractions, same strings as the app (GD R3 fix 4)
s = s.replace('Now it is getting interesting.', "Now it&#x27;s getting interesting.").replace('you would only ask', "you&#x27;d only ask")
s = re.sub(r'\n +', '\n', s)

print(f'''<!doctype html>
<html lang="en" data-kbd><head><meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<meta name="theme-color" content="#0C0722">
<title>Pixeldate · Dating, one pixel at a time</title>
<meta name="description" content="Pixeldate pairs you with someone at random. Photos and video calls start as 8 blurry blocks and get sharper as you both answer questions.">
<link rel="preload" href="{A}fonts/BricolageGrotesque-latin.woff2" as="font" type="font/woff2" crossorigin>
<link rel="icon" href="data:,">
<link rel="stylesheet" href="./src/styles/landing.css">
</head>
<body>
<!-- Static landing (design screens/src/landing.html, SPEC 01). No JavaScript; generated by tools/landing-from-design.py. -->
{s.strip()}
</body></html>''')
