// One-off transform (re-runnable): folds the pre-Player-Two CSS into a single file whose rules only
// reach elements inside <div class="legacy">. Lets the R1 kit (cascade layers) live alongside the
// onboarding + lobby screens until R2/R4 restyle them; delete src/styles/legacy.css then.
//   node tools/scope-legacy.mjs   → src/styles/legacy.css
import { readFileSync, writeFileSync } from 'node:fs'
const SRC = ['public/px/css/pixeldate-px.css', 'public/px/css/v3.css', 'legacy-src/app.css', 'legacy-src/type-v4.css']
const FONT = [[/"Pixeldate Sans"/g, '"Jersey 15"'], [/"Pixeldate Caps"/g, '"Bricolage Grotesque"'], [/"IBM Plex Sans"/g, '"Bricolage Grotesque"']]

function blocks(css) { // top-level split → [{pre, body}|{stmt}]
  const out = []; let i = 0
  while (i < css.length) {
    const b = css.indexOf('{', i), s = css.indexOf(';', i)
    if (b < 0) break
    if (s >= 0 && s < b && css.slice(i, s).trim().startsWith('@')) { out.push({ stmt: css.slice(i, s + 1).trim() }); i = s + 1; continue }
    let d = 1, j = b + 1
    while (d && j < css.length) { if (css[j] === '{') d++; else if (css[j] === '}') d--; j++ }
    out.push({ pre: css.slice(i, b).trim(), body: css.slice(b + 1, j - 1) }); i = j
  }
  return out
}
function splitSel(s) { const r = []; let d = 0, cur = ''; for (const c of s) { if (c === '(') d++; if (c === ')') d--; if (c === ',' && !d) { r.push(cur); cur = '' } else cur += c } r.push(cur); return r.map(x => x.trim()).filter(Boolean) }
function sel(x) {
  x = x.replace(/^body\.type-v(?:21|4)(?:\.type-v(?:21|4))?(?=\s|$)/, ':scope')
  x = x.replace(/^:scope\s+/, '')
  if (/^(html|body|:root)$/.test(x)) return ':scope'
  x = x.replace(/^(html|body)\s+/, '').replace(/:root/g, ':scope')
  return x
}
function urls(body, file) { return file.startsWith('public/px/css/') ? body.replace(/url\((['"]?)\.\.\//g, 'url($1/Pixeldate/px/') : body }
function walk(css, file, hoist) {
  let o = ''
  for (const b of blocks(css)) {
    if (b.stmt) continue // @import/@charset: none in practice
    if (b.pre.startsWith('@font-face')) continue // app ships only Jersey 15 + Bricolage
    if (b.pre.startsWith('@keyframes')) { hoist.push(`${b.pre}{${b.body}}`); continue }
    if (b.pre.startsWith('@')) { o += `${b.pre}{${walk(b.body, file, hoist)}}\n`; continue }
    o += `${[...new Set(splitSel(b.pre).map(sel))].join(',')}{${urls(b.body, file).trim()}}\n`
  }
  return o
}
const hoist = []; let body = ''
for (const f of SRC) body += `/* ${f} */\n` + walk(readFileSync(f, 'utf8').replace(/\/\*[\s\S]*?\*\//g, ''), f, hoist)
let out = `/* GENERATED by tools/scope-legacy.mjs from the pre-R1 stylesheets. Do not edit by hand.\n   Unlayered on purpose but fenced by @scope, so it cannot leak into the Player Two layers. */\n` +
  hoist.join('\n') + `\n@scope (.legacy){\n:scope{min-height:100dvh}\n${body}}\n`
for (const [a, b] of FONT) out = out.replace(a, b)
writeFileSync('src/styles/legacy.css', out)
console.log('legacy.css', out.length, 'bytes')
