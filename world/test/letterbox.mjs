await test('rules: race hides letters, first solve wins, pick scores fewer guesses, clock, coins', () => {
  let now = 1000; const c = () => ({ now, rnd: () => 0 })
  assert.ok(LB.wordCount.answers > 2000 && LB.wordCount.allowed > LB.wordCount.answers)
  assert.deepEqual(LB.mark('trace', 'crane'), ['absent', 'correct', 'correct', 'present', 'correct'])
  assert.deepEqual(LB.mark('crane', 'crane'), ['correct', 'correct', 'correct', 'correct', 'correct'])
  const s = LB.Letterbox.start(['a', 'b'], c())
  assert.equal(LB.Letterbox.act(s, 'a', { a: 'mode', w: 'race' }, c()), '')
  assert.equal(LB.Letterbox.act(s, 'b', { a: 'mode', w: 'pick' }, c()), '')
  assert.equal(s.phase, 'mode', 'a mismatch clears both choices')
  assert.equal(s.ps[0].choice, ''); assert.equal(s.ps[1].choice, '')
  now += 500; LB.Letterbox.act(s, 'a', { a: 'mode', w: 'race' }, c()); LB.Letterbox.act(s, 'b', { a: 'mode', w: 'race' }, c())
  assert.equal(s.phase, 'bet'); assert.equal(s.mode, 'race')
  assert.equal(LB.Letterbox.canBet(s, 'a', 7), 'bad-ante')
  LB.rig(s, 'crane')
  assert.equal(LB.Letterbox.commit(s, 'a', 5, c()), ''); assert.equal(s.phase, 'bet')
  now += 500; assert.equal(LB.Letterbox.commit(s, 'b', 0, c()), '')
  assert.equal(s.phase, 'play'); assert.equal(s.ps[0].target, 'crane'); assert.equal(s.ps[1].target, 'crane')
  assert.equal(LB.Letterbox.act(s, 'a', { a: 'guess', w: 'zz' }, c()), 'short')
  assert.equal(LB.Letterbox.act(s, 'a', { a: 'guess', w: 'qqqqq' }, c()), 'bad-word')
  now += 500; assert.equal(LB.Letterbox.act(s, 'a', { a: 'guess', w: 'trace' }, c()), '')
  const seen = LB.Letterbox.view(s, 'b', c())
  assert.equal(seen.opp[0].w, '', 'the other player does not see the letters')
  assert.equal(seen.reveal, '')
  assert.deepEqual(seen.opp[0].marks, ['absent', 'correct', 'correct', 'present', 'correct'])
  now += 500; assert.equal(LB.Letterbox.act(s, 'a', { a: 'guess', w: 'crane' }, c()), '')
  assert.equal(s.winner, 'a'); assert.equal(s.phase, 'over')
  assert.equal(LB.Letterbox.view(s, 'b', c()).reveal, 'crane')
  assert.deepEqual(s.pay, [{ uid: 'a', delta: 10 }])
  // pick: fewer guesses wins, same count is a draw
  const p = LB.Letterbox.start(['a', 'b'], c())
  LB.Letterbox.act(p, 'a', { a: 'mode', w: 'pick' }, c()); LB.Letterbox.act(p, 'b', { a: 'mode', w: 'pick' }, c())
  LB.Letterbox.commit(p, 'a', 0, c()); LB.Letterbox.commit(p, 'b', 0, c())
  assert.equal(p.phase, 'set')
  assert.equal(LB.Letterbox.act(p, 'a', { a: 'set', w: 'zzzzz' }, c()), 'bad-word')
  now += 500; assert.equal(LB.Letterbox.act(p, 'a', { a: 'set', w: 'world' }, c()), '')
  now += 500; assert.equal(LB.Letterbox.act(p, 'b', { a: 'set', w: 'crane' }, c()), '')
  assert.equal(p.phase, 'play'); assert.equal(p.ps[0].target, 'crane'); assert.equal(p.ps[1].target, 'world')
  now += 500; LB.Letterbox.act(p, 'a', { a: 'guess', w: 'crane' }, c())
  assert.equal(p.phase, 'play', 'the other player can still finish in fewer')
  now += 500; LB.Letterbox.act(p, 'b', { a: 'guess', w: 'trace' }, c())
  now += 500; LB.Letterbox.act(p, 'b', { a: 'guess', w: 'world' }, c())
  assert.equal(p.winner, 'a', 'one guess beats two'); assert.equal(p.phase, 'over')
  const show = LB.Letterbox.view(p, 'b', c())
  assert.equal(show.opp[0].w, 'crane', 'once it is over, pick mode shows the letters')
  // clock eats a guess
  const t = LB.Letterbox.start(['a', 'b'], c())
  LB.Letterbox.act(t, 'a', { a: 'mode', w: 'race' }, c()); LB.Letterbox.act(t, 'b', { a: 'mode', w: 'race' }, c())
  LB.rig(t, 'crane'); LB.Letterbox.commit(t, 'a', 0, c()); LB.Letterbox.commit(t, 'b', 0, c())
  now += LB.GUESS_MS; assert.ok(LB.Letterbox.tick(t, c())); assert.equal(t.ps[0].guesses.length, 1); assert.equal(t.ps[0].guesses[0].auto, true)
  // leaving forfeits
  const l = LB.Letterbox.start(['a', 'b'], c())
  LB.Letterbox.act(l, 'a', { a: 'mode', w: 'race' }, c()); LB.Letterbox.act(l, 'b', { a: 'mode', w: 'race' }, c())
  LB.rig(l, 'crane'); LB.Letterbox.commit(l, 'a', 1, c()); LB.Letterbox.commit(l, 'b', 1, c())
  LB.Letterbox.leave(l, 'a', c()); assert.equal(l.winner, 'b'); assert.ok(l.pay.some(x => x.uid === 'b' && x.delta === 2))
})

await test('room: two clients, race, hidden letters, stake, bad guess, chat', async () => {
  M.useMap('games'); const t = M.TABLES.find(x => x.kind === 'letterbox'); const seats = [...t.seats, ...t.extra]; M.useMap('cafe-landscape')
  const A = await J({ name: 'Ann' }), B = await J({ name: 'Bo' }), C = await J({ name: 'Cy' })
  await goSit(A, seats[0]); await goSit(B, seats[1])
  const g0 = await A.wait(() => lastGame(A)?.g === 'letterbox' && lastGame(A)); assert.equal(g0.phase, 'mode')
  A.send({ t: 'gstart', g: 'letterbox' }); assert.equal((await A.wait(() => A.last('gerr'))).why, 'bad')
  A.send({ t: 'gact', a: 'mode', w: 'race' }); B.send({ t: 'gact', a: 'mode', w: 'race' })
  assert.equal((await A.wait(() => lastGame(A)?.phase === 'bet' && lastGame(A))).phase, 'bet')
  const a0 = A.last('chips').bal
  const errs = () => A.events.filter(e => e.t === 'gerr').length
  const nErr = errs()
  A.send({ t: 'gact', a: 'bet', ante: 7 }); assert.equal((await A.wait(() => errs() > nErr && A.last('gerr'))).why, 'bad-ante')
  A.send({ t: 'gact', a: 'bet', ante: 5 }); B.send({ t: 'gact', a: 'bet', ante: 0 })
  const play = await A.wait(() => lastGame(A)?.phase === 'play' && lastGame(A), 4000); assert.ok(play)
  assert.equal(play.reveal, '')
  assert.equal((await A.wait(() => A.last('chips')?.bal === a0 - 5 && A.last('chips'), 3000)).bal, a0 - 5)
  A.send({ t: 'gact', a: 'guess', w: 'qqqqq' }); assert.equal((await A.wait(() => A.events.filter(e => e.t === 'gerr' && e.why === 'bad-word').length && A.last('gerr'))).why, 'bad-word')
  A.send({ t: 'gact', a: 'guess', w: 'crane' })
  const after = await B.wait(() => lastGame(B)?.opp?.length === 1 && lastGame(B), 3000)
  assert.ok(after); assert.equal(after.opp[0].marks.length, 5)
  if (after.phase !== 'over') assert.equal(after.opp[0].w, '', 'Bo sees colours, not letters')
  else assert.equal(after.reveal.length, 5)
  A.send({ t: 'say', text: 'letterbox table' })
  assert.equal((await B.wait(() => B.last('say') || B.last('said'))).text, 'letterbox table')
  await sleep(200); assert.ok(!C.events.some(e => e.text === 'letterbox table'))
  assert.ok(!A.text.join().includes('bot-'))
})
