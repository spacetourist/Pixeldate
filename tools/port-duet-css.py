def scope(sel):
    out = []
    for s in sel.split(','):
        s = s.strip(); s = re.sub(r'\.btn\b', '.w-btn', s)
        out.append('.w-duet ' + s if not s.startswith('@') else s)
    return ','.join(out)
def port(css):
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S); res, i = [], 0
    while True:
        j = css.find('{', i)
        if j < 0: break
        sel = css[i:j].strip()
        if sel.startswith('@keyframes'):
            depth, k = 1, j + 1
            while depth: depth += {'{': 1, '}': -1}.get(css[k], 0); k += 1
            res.append(sel.replace('pop', 'wdpop') + css[j:k]); i = k; continue
        k = css.find('}', j); body = css[j + 1:k].replace('animation:pop ', 'animation:wdpop ')
        res.append(scope(sel) + '{' + body + '}'); i = k + 1
    return '\n'.join(res)
with open(OUT, 'w') as f:
    f.write(HEAD + port(open(SRC + '/duet.css').read()) + '\n' + port(open(SRC + '/game.css').read()) + '\n')
