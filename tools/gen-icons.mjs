// Generates src/ui/icons.ts from the design pack's ASCII pixel grids (player-two/js/icons.js).
// Usage: node tools/gen-icons.mjs <path-to-icons.js>
import fs from 'node:fs'
const src = fs.readFileSync(process.argv[2], 'utf8')
const window = {}; new Function('window', src)(window)
const KEEP = 'heart lock chat cam spark send user down check eye call hangup mic skip stage compact alert cards winter spring summer autumn x plus'.split(' ')
let out = '// Generated by tools/gen-icons.mjs from the Player Two design pack. 1 unit = 1 art pixel.\nexport const ICONS = {\n'
for (const k of KEEP) {
  const m = window.ICONS[k]; if (!m) { console.warn('missing', k); continue }
  const h = m.length, w = Math.max(...m.map(r => r.length)); let d = ''
  // merge horizontal runs into rects
  m.forEach((row, y) => { let x = 0; while (x < row.length) { if (row[x] !== 'X') { x++; continue } let e = x; while (row[e] === 'X') e++; d += `M${x} ${y}h${e - x}v1h-${e - x}z`; x = e } })
  out += `  ${k}: [${w}, ${h}, '${d}'],\n`
}
out += '} as const satisfies Record<string, readonly [number, number, string]>\nexport type IconName = keyof typeof ICONS\n'
fs.writeFileSync('src/ui/icons.ts', out)
