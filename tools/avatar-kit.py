#!/usr/bin/env python3
"""Pixel-avatar kit codegen. GD's kit (design/pixeldate/pixel-avatar) stays the single source of truth:
  - sprites/kit.json  -> src/avatar/kit/kit.gen.ts   (palettes, option lists, samples)
  - tools/kit.py      -> src/avatar/kit/atlas.png     (every part layer as one indexed 24x32-cell atlas)
The TS compose() (src/avatar/kit/compose.ts) layers these cells exactly like kit.py's compose().
Usage: python3 tools/avatar-kit.py [KIT_DIR]   (default ../design/pixeldate/pixel-avatar)"""
import json, os, sys
from PIL import Image
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
KIT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, '..', 'design', 'pixeldate', 'pixel-avatar'))
sys.path.insert(0, os.path.join(KIT, 'tools'))
import kit as K  # noqa: E402

meta = json.load(open(os.path.join(KIT, 'sprites', 'kit.json')))
SLOTS = 'SsHhgTtnBbFfJjKWwELqrAaOYZG'   # every slot char kit.py draws with ('.' = empty)

cells = []  # (name, grid)
for b in K.BUILDS: cells.append((f'body.{b}', K.body(b)))
for t in K.TOPS:
    for b in K.BUILDS: cells.append((f'top.{t}.{b}', K.top(t, b)))
for b in K.BOTTOMS: cells.append((f'bottom.{b}', K.bottom(b)))
for s in K.SHOES: cells.append((f'shoes.{s}', K.shoes(s)))
for f in ('a', 'b'): cells.append((f'face.{f}', K.face(f)))
for b in K.BEARDS[1:]: cells.append((f'beard.{b}', K.beard(b)))
for h in K.HAIRS:
    hb, hf = K.hair(h); cells.append((f'hairB.{h}', hb)); cells.append((f'hairF.{h}', hf))
for a in K.ACCS[1:]: cells.append((f'acc.{a}', K.acc(a)))
g = K.blank(); K.rect(g, 7, 5, 7, 6, 'H'); K.rect(g, 15, 5, 15, 6, 'H'); cells.append(('hatHair', g))  # compose(): tufts under a hat

COLS = 12; rows = (len(cells) + COLS - 1) // COLS
im = Image.new('P', (COLS * K.W, rows * K.H), 0)
# palette index 0 = empty, i+1 = SLOTS[i]; colours are a debug ramp (red channel = index*8) so the decoder is exact
pal = [0, 0, 0] + sum(([(i + 1) * 8, 64 + (i * 37) % 160, 200 - (i * 5)] for i in range(len(SLOTS))), [])
im.putpalette(pal + [0] * (768 - len(pal)))
px = im.load()
for n, (name, grid) in enumerate(cells):
    ox, oy = (n % COLS) * K.W, (n // COLS) * K.H
    for y in range(K.H):
        for x in range(K.W):
            c = grid[y][x]
            if c != '.':
                if c not in SLOTS: raise SystemExit(f'unknown slot {c!r} in {name}')
                px[ox + x, oy + y] = SLOTS.index(c) + 1
out_png = os.path.join(ROOT, 'src', 'avatar', 'kit', 'atlas.png')
im.save(out_png, optimize=True, transparency=0)

ts = ['/* GENERATED by tools/avatar-kit.py from design/pixeldate/pixel-avatar (sprites/kit.json + tools/kit.py). Do not edit. */',
      f'export const GRID = {json.dumps(meta["grid"])} as const',
      f"export const EDGE = '{K.EDGE}'",
      f'export const SLOTS = {json.dumps(SLOTS)}',
      f'export const ATLAS_COLS = {COLS}',
      f'export const CELLS: Record<string, number> = {json.dumps({n: i for i, (n, _) in enumerate(cells)})}']
for k in ('builds', 'hairs', 'tops', 'bottoms', 'shoes', 'beards', 'accs'):
    ts.append(f'export const {k.upper()} = {json.dumps(meta[k])} as const')
ts.append('/** skin: base, shade, blush, mouth */')
ts.append(f'export const SKIN: Record<string, readonly [string, string, string, string]> = {json.dumps(meta["skin"])}')
ts.append('/** hair: base, shade, highlight */')
ts.append(f'export const HAIRC: Record<string, readonly [string, string, string]> = {json.dumps(meta["hair_colours"])}')
ts.append('/** cloth: base, shade, highlight */')
ts.append(f'export const CLOTH: Record<string, readonly [string, string, string]> = {json.dumps(meta["cloth"])}')
ts.append(f'export const FIXED: Record<string, string> = {json.dumps(K.FIXED)}')
ts.append('/** kit.py: compose() hides hair_front under a beanie/cap unless the style is one of these */')
ts.append(f"export const HAT_SHOWS = {json.dumps(['long', 'wavy', 'bob', 'afro'])}")
ts.append(f'export const BASE = {json.dumps(K.BASE)}')
ts.append(f'export const SAMPLES = {json.dumps(meta["samples"])}')
open(os.path.join(ROOT, 'src', 'avatar', 'kit', 'kit.gen.ts'), 'w').write('\n'.join(ts) + '\n')
# sanity: kit.json must agree with kit.py (GD regenerates both together)
assert meta['hair_colours'] == {k: list(v) for k, v in K.HAIRC.items()} and meta['cloth'] == {k: list(v) for k, v in K.CLOTH.items()}, 'kit.json out of date with kit.py'
print(f'{len(cells)} cells, atlas {im.size[0]}x{im.size[1]} {os.path.getsize(out_png)} B')
